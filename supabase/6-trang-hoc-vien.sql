-- GUANGYU HANYU — BẢN 6.5: TRANG HỌC VIÊN (tra cứu lớp bằng mã + học viên tự điền hồ sơ)
-- Chạy 1 lần trong Supabase → SQL Editor → New query → dán toàn bộ → Run.
-- Chỉ THÊM cột / bảng / hàm, không xoá hay sửa dữ liệu cũ. Chạy lại nhiều lần cũng không sao.

-- 1) Buổi học: thêm bài tập về nhà + link bài giảng
alter table buoi_hoc add column if not exists bai_tap text;
alter table buoi_hoc add column if not exists link_bai text;

-- 2) Bản tóm tắt công khai của từng lớp (web quản lý tự soạn & đăng; học viên chỉ đọc qua hàm xem_lop)
create table if not exists tra_cuu_lop (
  lop_id    bigint primary key references lop(id) on delete cascade,
  ma        text not null unique,
  du_lieu   jsonb not null default '{}'::jsonb,
  cap_nhat  timestamptz not null default now()
);

-- 3) Hồ sơ học viên gửi lên — chờ Thầy duyệt trong web quản lý rồi mới ghi vào hoc_vien
create table if not exists ho_so_gui (
  id          bigint generated by default as identity primary key,
  lop_id      bigint references lop(id) on delete cascade,
  hoc_vien_id bigint references hoc_vien(id) on delete cascade,
  ho_ten      text,
  sdt         text,
  ngay_sinh   date,
  muc_tieu    text,
  xu_ly       boolean not null default false,
  tao_luc     timestamptz not null default now()
);

-- Chỉ Thầy (đã đăng nhập) được đọc/ghi 2 bảng này
do $$ declare t text; begin
  foreach t in array array['tra_cuu_lop','ho_so_gui'] loop
    execute format('alter table %I enable row level security', t);
    execute format('drop policy if exists chi_thay on %I', t);
    execute format('create policy chi_thay on %I for all to authenticated using (true) with check (true)', t);
    execute format('grant select, insert, update, delete on %I to authenticated, service_role', t);
    execute format('revoke all on %I from anon', t);
  end loop;
end $$;
grant usage, select, update on all sequences in schema public to authenticated, service_role;

-- 4) Hàm cho học viên: xem lớp theo mã (chỉ trả bản tóm tắt của đúng lớp đó)
create or replace function xem_lop(p_ma text)
returns jsonb
language sql
security definer
set search_path = public
stable
as $$
  select t.du_lieu || jsonb_build_object('cap_nhat', t.cap_nhat)
  from tra_cuu_lop t
  where t.ma = upper(regexp_replace(coalesce(p_ma, ''), '[^A-Za-z0-9]', '', 'g'))
    and coalesce((t.du_lieu->>'bat')::boolean, true)
  limit 1;
$$;

-- 5) Hàm cho học viên: gửi hồ sơ (chỉ học viên thuộc lớp có mã; tối đa 5 lần/ngày/người)
create or replace function gui_ho_so(p_ma text, p_hoc_vien bigint, p_ho_ten text, p_sdt text, p_ngay_sinh date, p_muc_tieu text)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare v_lop bigint;
begin
  select t.lop_id into v_lop from tra_cuu_lop t
   where t.ma = upper(regexp_replace(coalesce(p_ma, ''), '[^A-Za-z0-9]', '', 'g'))
     and coalesce((t.du_lieu->>'bat')::boolean, true);
  if v_lop is null then return false; end if;
  if not exists (select 1 from lop_hoc_vien where lop_id = v_lop and hoc_vien_id = p_hoc_vien) then return false; end if;
  if (select count(*) from ho_so_gui where hoc_vien_id = p_hoc_vien and tao_luc > now() - interval '1 day') >= 5 then return false; end if;
  insert into ho_so_gui (lop_id, hoc_vien_id, ho_ten, sdt, ngay_sinh, muc_tieu)
  values (v_lop, p_hoc_vien, left(nullif(trim(p_ho_ten), ''), 80), left(nullif(trim(p_sdt), ''), 20), p_ngay_sinh, left(nullif(trim(p_muc_tieu), ''), 300));
  return true;
end;
$$;

revoke all on function xem_lop(text) from public;
revoke all on function gui_ho_so(text, bigint, text, text, date, text) from public;
grant execute on function xem_lop(text) to anon, authenticated;
grant execute on function gui_ho_so(text, bigint, text, text, date, text) to anon, authenticated;

notify pgrst, 'reload schema';
