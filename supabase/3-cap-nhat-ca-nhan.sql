create table if not exists thoi_quen (
  id        bigint generated by default as identity primary key,
  ten       text not null,
  loai      text default 'so',        -- 'so' (nhập số) | 'tich' (đánh dấu)
  don_vi    text,                     -- 'đ', 'phút', 'từ', 'trang'
  muc_tieu  numeric,                  -- mục tiêu mỗi ngày
  icon      text,
  mau       text,
  thu_tu    integer default 0,
  dang_dung boolean default true,
  created_at timestamptz default now()
);
create table if not exists thoi_quen_nhat_ky (
  id            bigint generated by default as identity primary key,
  thoi_quen_id  bigint not null references thoi_quen(id) on delete cascade,
  ngay          date not null,
  gia_tri       numeric default 1,
  unique (thoi_quen_id, ngay)
);
create table if not exists chi_tieu (
  id         bigint generated by default as identity primary key,
  ngay       date not null default current_date,
  so_tien    integer not null,
  loai       text default 'chi',      -- 'chi' | 'thu'
  danh_muc   text,
  ghi_chu    text,
  created_at timestamptz default now()
);
create index if not exists chi_tieu_ngay_idx on chi_tieu(ngay);

do $$
declare t text;
begin
  foreach t in array array['thoi_quen','thoi_quen_nhat_ky','chi_tieu']
  loop
    execute format('alter table %I enable row level security', t);
    execute format('drop policy if exists chi_thay on %I', t);
    execute format('create policy chi_thay on %I for all to authenticated using (true) with check (true)', t);
  end loop;
end $$;

create or replace function dong_bo_ma() returns void
language plpgsql security invoker as $$
declare t text; m bigint;
begin
  foreach t in array array['bang_gia','hoc_vien','lop','khoa_hoc','buoi_hoc','thanh_toan','cong_viec','thoi_quen','thoi_quen_nhat_ky','chi_tieu']
  loop
    execute format('select coalesce(max(id),0) from %I', t) into m;
    perform setval(pg_get_serial_sequence(t, 'id'), greatest(m, 1), m > 0);
  end loop;
end $$;
grant execute on function dong_bo_ma() to authenticated;
