-- ---------- BẢNG GIÁ (theo giờ) ----------
create table if not exists bang_gia (
  id          bigint generated by default as identity primary key,
  nhom        text not null,                 -- 'HSK 3.0' | 'Giao tiếp' | ...
  ten         text not null,                 -- 'HSK 1', 'Cơ bản'
  mo_ta       text,                          -- 'Quyển 1'
  ten_zh      text,                          -- tên tiếng Trung để in PNG
  don_gia_gio integer not null default 0,    -- VNĐ / giờ
  thu_tu      integer default 0,
  dang_dung   boolean default true
);

-- ---------- HỌC VIÊN ----------
create table if not exists hoc_vien (
  id         bigint generated by default as identity primary key,
  ma         text generated always as ('HV' || lpad(id::text, 4, '0')) stored unique,
  ho_ten     text not null,
  ten_goi    text,                           -- cách Thầy gọi: 'Chị Thuỳ', 'Anh Tùng'
  sdt        text,
  ngon_ngu   text default 'vi',              -- 'vi' | 'zh' : ngôn ngữ báo cáo mặc định
  ghi_chu    text,
  created_at timestamptz default now()
);

-- ---------- LỚP ----------
create table if not exists lop (
  id          bigint generated by default as identity primary key,
  ma          text generated always as ('L' || lpad(id::text, 4, '0')) stored unique,
  ten         text not null,                 -- tên lớp hiển thị
  loai        text default '1-1',            -- '1-1' | 'nhom'
  bang_gia_id bigint references bang_gia(id) on delete set null,
  trinh_do    text,                          -- in lên PNG (VD: 'HSK 2')
  mau         text,                          -- màu trên lịch
  ngon_ngu    text default 'vi',             -- ngôn ngữ PNG mặc định
  dang_hoat_dong boolean default true,
  ghi_chu     text,
  created_at  timestamptz default now()
);

create table if not exists lop_hoc_vien (
  lop_id      bigint references lop(id) on delete cascade,
  hoc_vien_id bigint references hoc_vien(id) on delete cascade,
  primary key (lop_id, hoc_vien_id)
);

-- ---------- KHOÁ HỌC (mỗi lần đóng tiền = 1 khoá) ----------
create table if not exists khoa_hoc (
  id                bigint generated by default as identity primary key,
  ma                text generated always as ('K' || lpad(id::text, 4, '0')) stored unique,
  lop_id            bigint not null references lop(id) on delete cascade,
  giao_trinh        text,
  muc_tieu          text,
  ngay_bat_dau      date,
  so_buoi           integer not null default 8,     -- số buổi đã đóng tiền
  thoi_luong_phut   integer default 90,              -- thời lượng mặc định 1 buổi
  don_gia_gio       integer,                         -- đơn giá tham chiếu
  hoc_phi           integer not null default 0,      -- học phí khoá (cả lớp)
  buoi_chuyen_sang  integer default 0,               -- buổi dư từ khoá trước (+) hoặc học trước (−)
  gia_tri_chuyen_sang integer default 0,             -- giá trị VNĐ của các buổi chuyển sang
  buoi_chuyen_di    integer default 0,               -- buổi dư đã chuyển sang khoá sau
  khoa_truoc_id     bigint references khoa_hoc(id) on delete set null,
  ket_thuc          boolean default false,           -- đã đóng khoá
  lich_hoc          text,                            -- VD: 'T3 – T5, 20:00' (in lên PNG 01)
  da_gui_thong_tin  boolean default false,           -- đã gửi PNG 01 cho học viên
  ghi_chu           text,
  created_at        timestamptz default now()
);

-- ---------- BUỔI HỌC: vừa là LỊCH DẠY vừa là NHẬT KÝ ----------
create table if not exists buoi_hoc (
  id              bigint generated by default as identity primary key,
  ma              text generated always as ('B' || lpad(id::text, 5, '0')) stored unique,
  lop_id          bigint not null references lop(id) on delete cascade,
  khoa_id         bigint references khoa_hoc(id) on delete set null,
  ngay            date not null,
  gio_bat_dau     time,
  thoi_luong_phut integer default 90,
  trang_thai      text default 'du_kien',   -- 'du_kien' | 'da_day' | 'nghi' | 'huy'
  tinh_phi        boolean default true,     -- buổi đã dạy có trừ buổi/tính phí không
  noi_dung        text,
  ghi_chu         text,
  created_at      timestamptz default now()
);
create index if not exists buoi_hoc_ngay_idx on buoi_hoc(ngay);

-- ---------- THANH TOÁN ----------
create table if not exists thanh_toan (
  id         bigint generated by default as identity primary key,
  ma         text generated always as ('GD' || lpad(id::text, 4, '0')) stored unique,
  khoa_id    bigint references khoa_hoc(id) on delete set null,
  lop_id     bigint references lop(id) on delete cascade,
  ngay       date not null default current_date,
  so_tien    integer not null,
  hinh_thuc  text default 'Chuyển khoản',
  ghi_chu    text,
  created_at timestamptz default now()
);

-- ---------- CÔNG VIỆC ----------
create table if not exists cong_viec (
  id        bigint generated by default as identity primary key,
  tieu_de   text not null,
  nhom      text default 'Dạy học',
  han       date,
  uu_tien   integer default 2,        -- 1 cao, 2 vừa, 3 thấp
  lop_id    bigint references lop(id) on delete set null,
  xong      boolean default false,
  ghi_chu   text,
  created_at timestamptz default now()
);

-- ---------- CÀI ĐẶT ----------
create table if not exists cai_dat (
  khoa  text primary key,
  gia_tri jsonb
);

-- Bổ sung cột nếu database đã tạo từ phiên bản trước
alter table khoa_hoc add column if not exists lich_hoc text;
alter table khoa_hoc add column if not exists da_gui_thong_tin boolean default false;

-- =====================================================================
--  BẢO MẬT: chỉ tài khoản đã đăng nhập (Thầy) mới đọc/ghi được
